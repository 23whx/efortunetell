const BRANCH_PINYIN: Record<string, string> = {
  子: 'Zi', 丑: 'Chou', 寅: 'Yin', 卯: 'Mao', 辰: 'Chen', 巳: 'Si',
  午: 'Wu', 未: 'Wei', 申: 'Shen', 酉: 'You', 戌: 'Xu', 亥: 'Hai',
};
const BRANCH_ANIMAL = '鼠牛虎兔龙蛇马羊猴鸡狗猪';
const BRANCHES = '子丑寅卯辰巳午未申酉戌亥';

/** Builds a translator; `en=false` returns the Chinese term unchanged. */
export function almanacTranslator(en: boolean) {
  const tr = (map: Record<string, string>) => (v: string | null | undefined) => (v && en ? map[v] ?? v : v ?? '');
  return {
    en,
    yiJi: tr(YI_JI_EN),
    jianChu: (v: string | null | undefined) => (v && en && JIAN_CHU_EN[v] ? `${JIAN_CHU_EN[v]} (${v})` : v ?? ''),
    tianShen: tr(TIAN_SHEN_EN),
    xiu: (v: string | null | undefined) => (v && en && XIU_EN[v] ? `${XIU_EN[v]} (${v})` : v ?? ''),
    luck: (v: string | null | undefined) => (en ? (v === '吉' ? 'auspicious' : v === '凶' ? 'inauspicious' : v ?? '') : v ?? ''),
    direction: tr(DIRECTION_EN),
    solarTerm: tr(SOLAR_TERM_EN),
    /** "(乙卯)兔" → "Rabbit (乙卯)" */
    chong: (v: string | null | undefined) => {
      if (!v || !en) return v ?? '';
      const m = /^\((.+)\)(.)$/.exec(v);
      return m ? `${ANIMAL_EN[m[2]] ?? m[2]} (${m[1]})` : v;
    },
    /** "子" → "Zi (Rat) hour" */
    hour: (zhi: string) => (en ? `${BRANCH_PINYIN[zhi]} · ${ANIMAL_EN[BRANCH_ANIMAL[BRANCHES.indexOf(zhi)]]}` : `${zhi}时`),
  };
}
